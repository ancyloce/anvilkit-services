#!/bin/sh
# Writes images.env (the digest-pinned image references compose.yaml reads) from a
# SIGNED release manifest of the release workflow (.github/workflows/release.yml,
# tools/release-artifacts.py): every owned image at the digest the manifest records,
# under the registry the manifest was pushed to. Nothing is pulled or built here;
# `docker compose pull` on the server then fetches exactly these digests.
#
#   sh deploy/compose/images.sh outputs/qualification/<run>/release/release-manifest.json [> images.env]
#
# Refuses a manifest whose status is BLOCKED or that carries findings, and a
# manifest whose images were pushed to the development registry (localhost:5001 /
# anvilkit-dev-registry:5000): those are not CI-published images.
set -eu
MANIFEST=${1:?release-manifest.json}
python3 - "$MANIFEST" <<'EOF'
import json, sys
m = json.load(open(sys.argv[1]))
status, findings = m.get("status"), m.get("findings") or []
if status not in ("SIGNED", "SIGNED_DEVELOPMENT_ONLY") or findings:
    sys.exit(f"refused: manifest status {status} with {len(findings)} finding(s)")
registry = (m.get("registry") or {}).get("reference") or ""
if registry in ("localhost:5001", "anvilkit-dev-registry:5000") or not registry:
    sys.exit(f"refused: images pushed to the development registry ({registry!r}), not a CI-published registry")
names = {
    "anvilkit-agent-api": "IMAGE_API", "anvilkit-agent-control": "IMAGE_CONTROL", "anvilkit-agent-workflow": "IMAGE_WORKFLOW",
    "anvilkit-agent-model-proxy": "IMAGE_MODEL_PROXY", "anvilkit-agent-knowledge": "IMAGE_KNOWLEDGE",
    "anvilkit-knowledge-forwarder": "IMAGE_KNOWLEDGE_FORWARDER", "anvilkit-agent-mcp": "IMAGE_MCP",
    "anvilkit-agent-background-worker": "IMAGE_BACKGROUND_WORKER", "anvilkit-agent-inference": "IMAGE_INFERENCE",
    "anvilkit-migration": "IMAGE_MIGRATION",
}
images = m.get("images") or {}
missing = [n for n in names if n not in images]
if missing:
    sys.exit(f"refused: the manifest lacks {', '.join(missing)}")
print(f"# generated by deploy/compose/images.sh from release {m.get('run')} (status {status}); do not edit")
print(f"ANVILKIT_RELEASE={m.get('run')}")
print(f"ANVILKIT_IMAGE_REGISTRY={registry}")
for name, var in names.items():
    img = images[name]
    ref = img["reference"]
    if "@sha256:" not in ref or not ref.startswith(registry + "/"):
        sys.exit(f"refused: {name} reference {ref!r} is not a digest reference under {registry}")
    print(f"{var}={ref}")
EOF
