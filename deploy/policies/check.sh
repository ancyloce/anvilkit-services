#!/bin/sh
# Offline and cluster checks of the P09 admission policies.
#
#   sh deploy/policies/check.sh              # offline: kyverno apply (CLI) against the launcher's fixtures and their mutations
#   sh deploy/policies/check.sh --cluster    # in addition: server-side dry-run admission against the development cluster
#
# The fixtures are the launcher's renders (services/agent/workflow,
# TestRenderPolicyFixtures; the parser's by Knowledge) committed under
# deploy/policies/tests/resources. Since P3.3 this script never rewrites them:
# it renders into a scratch directory, fails on any difference from the
# committed files (drift between the launchers and the tested fixtures), and
# tests the committed files; the negative cases are derived from them by
# tests/mutate.py. ANVILKIT_POLICY_FIXTURES names another fixture directory
# (the drift negative of the self-check). Offline results are policy
# evaluation by the pinned Kyverno CLI (1.19.1), not admission; --cluster asks the
# development cluster's admission chain (Kyverno's webhook) with server-side dry
# runs and records that separately: Pods with the cluster administrator's context
# (the launcher identity cannot create Pods), Jobs with the launcher's own
# identity (ANVILKIT_LAUNCHER_KUBECONFIG, the kubeconfig deploy/dev/up.sh writes),
# which is what the Job policy and the autogenerated template rules admit or deny
# for the real launcher. Exit 1 on any unexpected outcome.
set -eu
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
POLICIES="$ROOT/deploy/policies"
KYVERNO=${ANVILKIT_KYVERNO_CLI:-$ROOT/.local/dev/kyverno/kyverno}
PY=${ANVILKIT_PYTHON_ENV:-$ROOT/.local/verification-venv/bin/python}
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
export PATH="$PATH:$(go env GOPATH)/bin"

test -x "$KYVERNO" || { echo "UNEXECUTED: kyverno CLI not found at $KYVERNO (deploy/dev/up.sh downloads 1.19.1)" >&2; exit 2; }
"$KYVERNO" version | head -1
FIXTURES=${ANVILKIT_POLICY_FIXTURES:-$POLICIES/tests/resources}
mkdir -p "$WORK/rendered"
(cd "$ROOT/services/agent/workflow" && ANVILKIT_RENDER_POLICY_FIXTURES="$WORK/rendered" go test -count=1 -run TestRenderPolicyFixtures ./internal/adapters/kubernetes/ >/dev/null)
# P0.7: the parser Job as Knowledge's launcher renders it.
(cd "$ROOT/services/agent/knowledge" && ANVILKIT_RENDER_POLICY_FIXTURES="$WORK/rendered" npx vitest run test/parse.test.ts >/dev/null) \
  || { echo "UNEXECUTED: the parser fixtures did not render (services/agent/knowledge: pnpm install)" >&2; exit 2; }
failures=0
total=1
if diff -r -q "$WORK/rendered" "$FIXTURES" > "$WORK/drift.txt"; then
  printf 'PASS fixtures %-35s %s\n' "rendered-equals-committed" "$(ls "$FIXTURES" | wc -l | tr -d ' ') files"
else
  printf 'FAIL fixtures %-35s the launchers render differently from the committed fixtures\n' "rendered-equals-committed"
  sed 's/^/      | /' "$WORK/drift.txt"
  diff -r -u "$FIXTURES" "$WORK/rendered" | head -n 40 | sed 's/^/      | /'
  failures=$((failures+1))
fi
# The launcher renders the fixtures with the development registry; a digest is
# the identity and the registry the environment's placement, so another
# environment's values (ANVILKIT_POLICY_VALUES) place the same digests in its
# own registry: its first components prefix, its first parsing prefix for the
# parser's objects. The placed copy feeds the cases and the cluster lifecycle
# probe; foreign registries of the negative cases stay foreign.
cat > "$WORK/place.py" <<'PLACE'
import json, pathlib, sys
import yaml
values = yaml.safe_load(open(sys.argv[1])) or {}
registries = values.get("registries") or {}
def first(entries):
    return next((e for e in entries or [] if e.endswith("/")), None)
components, parsing = first(registries.get("components")), first(registries.get("parsing"))
for f in pathlib.Path(sys.argv[2]).glob("*.yaml"):
    text = f.read_text()
    place = parsing if "anvilkit-parsing" in text else components
    if place and "localhost:5001/" in text:
        f.write_text(text.replace("localhost:5001/", place))
# The development-state profile's valid cases pass only where the environment
# lists that profile; elsewhere its admission refuses them.
exp = pathlib.Path(sys.argv[2]) / "expectations.json"
listed = values.get("developmentProfiles") or []
if exp.exists():
    e = json.loads(exp.read_text())
    unlisted = {"validator-source-dev-v1": ("valid-validator-source-dev-job", "valid-validator-source-dev-pod"),
                "codegen-team-dev-v1": ("valid-team-dev-job", "valid-team-dev-pod", "placement-dropped")}
    for profile, cases in unlisted.items():
        if profile not in listed:
            for case in cases:
                if case in e:
                    e[case] = "fail"
    exp.write_text(json.dumps(e))
PLACE
cp -R "$FIXTURES" "$WORK/resources"
if [ -n "${ANVILKIT_POLICY_VALUES:-}" ]; then
  "$PY" "$WORK/place.py" "$ANVILKIT_POLICY_VALUES" "$WORK/resources"
fi
"$PY" "$POLICIES/tests/mutate.py" "$WORK/resources" "$WORK/cases"
if [ -n "${ANVILKIT_POLICY_VALUES:-}" ]; then
  "$PY" "$WORK/place.py" "$ANVILKIT_POLICY_VALUES" "$WORK/cases"
fi
# The policies are the Job-admission chart rendered with an environment's
# values (the development foundation's unless ANVILKIT_POLICY_VALUES names
# another environment's file).
HELM=${ANVILKIT_HELM:-$ROOT/.local/bin/helm}
test -x "$HELM" || HELM=$(command -v helm) || { echo "UNEXECUTED: helm not found" >&2; exit 2; }
"$HELM" template anvilkit-job-admission "$POLICIES/chart" -f "${ANVILKIT_POLICY_VALUES:-$ROOT/deploy/dev/values/anvilkit-job-admission.yaml}" \
  --show-only templates/components-jobs.yaml --show-only templates/parsing-jobs.yaml --show-only templates/registries.yaml > "$WORK/policies.yaml"
# kyverno apply evaluates namespace selectors from a values file offline.
cat > "$WORK/values.yaml" <<VALUES
apiVersion: cli.kyverno.io/v1alpha1
kind: Values
metadata:
  name: anvilkit-components
namespaceSelector:
  - name: anvilkit-components
    labels:
      kubernetes.io/metadata.name: anvilkit-components
  - name: anvilkit-parsing
    labels:
      kubernetes.io/metadata.name: anvilkit-parsing
VALUES
for f in "$WORK"/cases/*.yaml; do
  case=$(basename "$f" .yaml)
  expect=$("$PY" -c "import json,sys; print(json.load(open('$WORK/cases/expectations.json'))['$case'])")
  total=$((total+1))
  out=$("$KYVERNO" apply "$WORK/policies.yaml" --resource "$f" --values-file "$WORK/values.yaml" 2>&1 || true)
  if echo "$out" | grep -qE 'fail: [1-9]'; then got=fail; elif echo "$out" | grep -qE 'pass: [1-9]'; then got=pass; else got="error"; fi
  if [ "$got" = "$expect" ]; then
    printf 'PASS offline %-36s %s\n' "$case" "$got"
  else
    printf 'FAIL offline %-36s expected %s, got %s\n' "$case" "$expect" "$got"
    echo "$out" | tail -n 6 | sed 's/^/      | /'
    failures=$((failures+1))
  fi
done
# P0.8: the development-state candidate profile is admitted only where the
# environment lists it: the same chart without the list (every environment
# but the development foundation) denies the launcher's own development Pod.
"$HELM" template anvilkit-job-admission "$POLICIES/chart" -f "${ANVILKIT_POLICY_VALUES:-$ROOT/deploy/dev/values/anvilkit-job-admission.yaml}" \
  --set developmentProfiles=null --show-only templates/components-jobs.yaml --show-only templates/registries.yaml > "$WORK/policies-nodev.yaml"
total=$((total+1))
out=$("$KYVERNO" apply "$WORK/policies-nodev.yaml" --resource "$WORK/cases/valid-validator-source-dev-pod.yaml" --values-file "$WORK/values.yaml" 2>&1 || true)
if echo "$out" | grep -qE 'fail: [1-9]'; then
  printf 'PASS offline %-36s fail (no development profile listed)\n' "validator-source-dev-unlisted"
else
  printf 'FAIL offline %-36s expected fail without the development list\n' "validator-source-dev-unlisted"
  echo "$out" | tail -n 6 | sed 's/^/      | /'
  failures=$((failures+1))
fi
if [ "${1:-}" = "--cluster" ]; then
  CTX=${ANVILKIT_DEV_KUBE_CONTEXT:-kind-anvilkit-dev}
  # The administrator's context lives in the admin kubeconfig, as for the
  # deploy/dev chart scripts; a sourced .local/dev/env.sh points KUBECONFIG
  # at the launcher's, which has no such context, and every admin dry run
  # would then be "rejected" for that reason instead of by a policy.
  ADMIN_KUBECONFIG=${ANVILKIT_DEV_ADMIN_KUBECONFIG:-$HOME/.kube/config}
  kubectl --kubeconfig "$ADMIN_KUBECONFIG" --context "$CTX" get --raw /readyz >/dev/null 2>&1 \
    || { echo "UNEXECUTED: the administrator context $CTX does not answer through $ADMIN_KUBECONFIG" >&2; exit 2; }
  LAUNCHER=${ANVILKIT_LAUNCHER_KUBECONFIG:-$ROOT/.local/dev/launcher.kubeconfig}
  # The parser namespace's launcher is Knowledge's identity (P15/P0.7).
  PARSER_LAUNCHER=${ANVILKIT_PARSER_LAUNCHER_KUBECONFIG:-$ROOT/.local/dev/knowledge-launcher.kubeconfig}
  test -r "$LAUNCHER" || { echo "UNEXECUTED: launcher kubeconfig not found at $LAUNCHER (deploy/dev/up.sh writes it)" >&2; exit 2; }
  # The launchers' tokens last 24 h (deploy/dev/up.sh): an expired one makes every
  # launcher dry run "rejected" as Unauthorized instead of by a policy.
  can_launch() {
    [ "$(kubectl --kubeconfig "$1" -n "$2" auth can-i create jobs 2>/dev/null)" = yes ] \
      || { echo "UNEXECUTED: the launcher identity of $1 cannot create Jobs in $2 (expired token? deploy/dev/up.sh mints it)" >&2; exit 2; }
  }
  can_launch "$LAUNCHER" anvilkit-components
  can_launch "$PARSER_LAUNCHER" anvilkit-parsing
  gvisor=yes
  kubectl --kubeconfig "$ADMIN_KUBECONFIG" --context "$CTX" get runtimeclass gvisor >/dev/null 2>&1 || gvisor=no
  for f in "$WORK"/cases/*.yaml; do
    case=$(basename "$f" .yaml)
    expect=$("$PY" -c "import json,sys; print(json.load(open('$WORK/cases/expectations.json'))['$case'])")
    if { [ "$case" = valid-candidate-pod ] || [ "$case" = valid-validator-source-pod ] || [ "$case" = valid-preview-build-pod ] || [ "$case" = valid-team-pod ]; } && [ "$gvisor" = no ]; then
      # The API server refuses a Pod whose RuntimeClass does not exist: on a
      # cluster without gVisor the candidate profile cannot be admitted at
      # all, which is the state P09 records (the profile stays disabled);
      # P2.4's preview-build-v1 and codegen-team-v1 Pods likewise.
      printf 'UNEXECUTED cluster %-29s no gVisor RuntimeClass on this cluster; the API server refuses the Pod before Kyverno decides\n' "$case"
      continue
    fi
    total=$((total+1))
    if grep -q '^kind: Job$' "$f"; then
      who=launcher
      kc=$LAUNCHER
      if grep -q '^  namespace: anvilkit-parsing$' "$f"; then kc=$PARSER_LAUNCHER; fi
      if out=$(kubectl --kubeconfig "$kc" create --dry-run=server -f "$f" 2>&1); then got=pass; else got=fail; fi
    else
      who=admin
      if out=$(kubectl --kubeconfig "$ADMIN_KUBECONFIG" --context "$CTX" create --dry-run=server -f "$f" 2>&1); then got=pass; else got=fail; fi
    fi
    if [ "$got" = "$expect" ]; then
      reason=admitted
      if [ "$got" = fail ]; then
        if echo "$out" | grep -q 'denied.*request\|denied the request'; then reason=policy;
        elif echo "$out" | grep -q 'is invalid\|Forbidden: cannot be set on create'; then reason=api-structural;
        else reason=other-rejection; fi
      fi
      printf 'PASS cluster/%-8s %-36s %s (%s)\n' "$who" "$case" "$got" "$reason"
      # F1/F2 regressions must reach the policy with a structurally valid
      # Job through the real launcher, not pass on an unrelated API error.
      case "$case" in
        job-node-name|job-scheduler-unreviewed|job-*-resources-*|job-*-limits-*|job-*-requests-*|job-*-size-*|job-*-medium-*|job-parser-*)
          if [ "$reason" != policy ]; then
            printf 'FAIL expected policy rejection: %s\n%s\n' "$case" "$out"
            failures=$((failures+1))
          fi ;;
      esac
    else
      printf 'FAIL cluster/%-8s %-36s expected %s, got %s\n' "$who" "$case" "$expect" "$got"
      echo "$out" | tail -n 4 | sed 's/^/      | /'
      failures=$((failures+1))
    fi
  done
  KUBECONFIG="$ADMIN_KUBECONFIG" "$PY" "$POLICIES/tests/mutate.py" --cluster-lifecycle "$WORK/resources" "$CTX" "$LAUNCHER" || failures=$((failures+1))
fi
echo "policy checks: $total cases, $failures failures"
[ "$failures" -eq 0 ]
